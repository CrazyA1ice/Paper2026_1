replacements, span_changes = {}, []
for key, before, after, reason, category in edits:
    pi, si = map(int, key.split('.'))
    current = replacements.get(key, {}).get('after', records[pi]['parts'][si]['text'])
    assert current.count(before) == 1, (key, before)
    current = current.replace(before, after, 1)
    if key not in replacements:
        replacements[key] = {'after': current, 'reason': reason}
    else:
        replacements[key]['after'] = current
        replacements[key]['reason'] += ' ' + reason
    span_changes.append({'paragraph': pi, 'segment': si, 'before': before, 'after': after,
                         'reason': reason, 'category': category})
(QA / 'replacements.json').write_text(json.dumps(replacements, ensure_ascii=False, indent=2), encoding='utf-8')
(QA / 'span_changes.json').write_text(json.dumps(span_changes, ensure_ascii=False, indent=2), encoding='utf-8')

