def paragraph_text(i, revised=False):
    return ''.join(replacements[f'{i}.{j}']['after'] if revised and f'{i}.{j}' in replacements else p.get('text', '')
                   for j, p in enumerate(records[i]['parts']))
scan_indices = [i for i in range(12, 117) if len(paragraph_text(i)) > 35 and not paragraph_text(i).startswith(('注：', '图', '表'))]
for label, revised in [('before', False), ('draft', True)]:
    (QA / f'editorial_{label}.txt').write_text('\n\n'.join(paragraph_text(i, revised) for i in scan_indices), encoding='utf-8')
