def find(prefix):
    xs = [p for p in doc.paragraphs if p.text.startswith(prefix)]
    if len(xs) != 1:
        raise RuntimeError(f"{prefix!r}: {len(xs)} matches")
    return xs[0]

def set_text(p, text):
    first = p.runs[0] if p.runs else p.add_run()
    first.text = text
    for r in p.runs[1:]:
        r.text = ""

def repl(prefix, text):
    p = find(prefix)
    set_text(p, text)
    return p

